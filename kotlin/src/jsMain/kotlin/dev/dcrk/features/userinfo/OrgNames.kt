private val legalForms = Regex("""주식회사|유한회사|유한책임회사|㈜|재단법인|사단법인|\([^)]*\)""")
private val orgSpaces = Regex("""\s+""")

internal fun shortenOrg(name: String): String {
    val base = name.replace(legalForms, "").replace(orgSpaces, " ").trim()
    if (base.isEmpty()) return name
    orgPresets[base]?.let { return it }
    val prefix = orgPrefixes.firstOrNull { base.startsWith(it.first) }
    val normalized = if (prefix == null) base else prefix.second + base.drop(prefix.first.length)
    return orgRules.fold(normalized) { current, (pattern, replacement) -> current.replace(pattern, replacement) }
}
